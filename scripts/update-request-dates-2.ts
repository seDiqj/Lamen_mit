async function updateRequestDates() {
  console.log('Updating additional request dates...');
  let updated = 0;
  
  for (const [appId, date] of Object.entries(requestDates)) {
    await db.update(loans)
      .set({ requestDate: date })
      .where(eq(loans.applicationId, appId));
    updated++;
  }
  
  console.log(`Updated ${updated} loans with request dates`);
  process.exit(0);
}

